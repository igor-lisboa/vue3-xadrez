// @vitest-environment node
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { afterEach, describe, expect, it } from 'vitest'
import {
  diffOutputs,
  findStale,
  GENERATED_MARKER,
  KEBAB_CASE,
  npmScriptsMentioned,
  parseFrontmatter,
  renderClaudeAgent,
  renderClaudeSkill,
  renderCodexAgent,
  renderCopilotAgent,
  repoPathsMentioned,
  validateCanonical,
  type CanonicalItem,
} from '../../scripts/lib/agents.mjs'

function item(
  overrides: Partial<CanonicalItem> & { data?: Record<string, string> },
): CanonicalItem {
  return {
    folder: 'sample',
    path: '.agents/agents/sample.md',
    body: 'Do the work.\n',
    ...overrides,
    data: {
      name: 'sample',
      description: 'Sample agent. Use it for tests.',
      tools: 'read',
      ...overrides.data,
    },
  }
}

describe('parseFrontmatter', () => {
  it('reads plain and quoted values and keeps the body', () => {
    const parsed = parseFrontmatter('---\nname: a\ndescription: "Uses: a colon"\n---\n\nBody\n')
    expect(parsed.data).toEqual({ name: 'a', description: 'Uses: a colon' })
    expect(parsed.body).toBe('Body\n')
  })

  it('accepts Windows line endings', () => {
    expect(parseFrontmatter('---\r\nname: a\r\n---\r\nBody\r\n')).toEqual({
      data: { name: 'a' },
      body: 'Body\n',
    })
  })

  it('rejects a file without frontmatter and lines it cannot read', () => {
    expect(() => parseFrontmatter('# Title')).toThrow('missing frontmatter')
    expect(() => parseFrontmatter('---\n- item\n---\nBody')).toThrow('unsupported frontmatter')
  })
})

describe('validateCanonical', () => {
  const valid = { skills: [], agents: [item({})] }

  it('accepts a valid agent', () => {
    expect(validateCanonical(valid)).toEqual([])
  })

  it('reports every kind of problem', () => {
    const problems = validateCanonical({
      skills: [
        item({ folder: 'Bad_Name', path: 'a', data: { name: 'Bad_Name', description: '' } }),
        item({ folder: 'other', path: 'b', data: { name: 'different', description: 'x' } }),
        item({
          folder: 'empty',
          path: 'c',
          body: '  \n',
          data: { name: 'empty', description: 'x' },
        }),
      ],
      agents: [
        item({ path: 'd', data: { name: 'sample', description: 'x', tools: 'read, fly' } }),
        item({ path: 'e', data: { name: 'sample', description: 'x', tools: '' } }),
      ],
    })
    expect(problems).toEqual(
      expect.arrayContaining([
        'a: missing description',
        'a: name "Bad_Name" is not kebab-case',
        'b: name "different" does not match "other"',
        'c: empty body',
        'd: unknown tool "fly"',
        'e: missing tools',
        'e: "sample" is used twice',
      ]),
    )
  })

  it('accepts only kebab-case names', () => {
    expect(['add-screen', 'verify', 'a1-b2'].every((name) => KEBAB_CASE.test(name))).toBe(true)
    expect(['Add', 'a_b', '-a', 'a--b', '1a'].some((name) => KEBAB_CASE.test(name))).toBe(false)
  })
})

describe('renderers', () => {
  const reviewer = item({ data: { name: 'sample', description: 'x', tools: 'read, search, run' } })
  const writer = item({ data: { name: 'sample', description: 'x', tools: 'read, edit, web' } })

  it('map the neutral tools to Claude tool names', () => {
    expect(renderClaudeAgent(reviewer)).toContain('tools: Read, Grep, Glob, Bash\n')
    expect(renderClaudeAgent(writer)).toContain('tools: Read, Edit, Write, WebFetch\n')
  })

  it('map the neutral tools to Copilot aliases', () => {
    expect(renderCopilotAgent(reviewer)).toContain('tools: ["read", "search", "execute"]\n')
    expect(renderCopilotAgent(writer)).toContain('tools: ["read", "edit", "web"]\n')
  })

  it('quote a description that YAML would misread, and mark the file as generated', () => {
    const tricky = item({ data: { name: 'sample', description: 'Use it: now', tools: 'read' } })
    const text = renderClaudeAgent(tricky)
    expect(text).toContain('description: "Use it: now"\n')
    expect(text).toContain(GENERATED_MARKER)
    expect(text.startsWith('---\n')).toBe(true)
  })

  it('write a skill whose frontmatter is only name and description', () => {
    const text = renderClaudeSkill(item({ data: { name: 'sample', description: 'x' } }))
    expect(Object.keys(parseFrontmatter(text).data)).toEqual(['name', 'description'])
  })

  it('tell Codex that an agent without edit is read-only, since TOML has no tools key', () => {
    expect(renderCodexAgent(reviewer)).toContain('This agent is read-only')
    expect(renderCodexAgent(writer)).not.toContain('read-only')
    expect(renderCodexAgent(reviewer)).toMatch(/^# .*Generated by/)
    expect(renderCodexAgent(reviewer)).toContain('name = "sample"')
  })

  it('refuse a body that would end the TOML string early', () => {
    const broken = item({ body: "it's '''bad'''\n" })
    expect(() => renderCodexAgent(broken)).toThrow('three single quotes')
  })
})

describe('mention finders', () => {
  it('find npm scripts, also with a colon', () => {
    expect(npmScriptsMentioned('Run `npm run check` then npm run sync:agents.')).toEqual([
      'check',
      'sync:agents',
    ])
  })

  it('find repository paths in backticks and skip globs and placeholders', () => {
    const text = '`src/a.ts` `tests/**/*.ts` `src/views/<Name>View.vue` `not/a/path.ts` `docs/x.md`'
    expect(repoPathsMentioned(text)).toEqual(['src/a.ts', 'docs/x.md'])
  })
})

describe('stale and changed files', () => {
  const folders: string[] = []
  afterEach(() => folders.splice(0).forEach((dir) => rmSync(dir, { recursive: true, force: true })))

  function temporaryRoot(): string {
    const dir = mkdtempSync(join(tmpdir(), 'agent-files-'))
    folders.push(dir)
    return dir
  }

  function write(base: string, relative: string, content: string): void {
    mkdirSync(dirname(join(base, relative)), { recursive: true })
    writeFileSync(join(base, relative), content, 'utf8')
  }

  it('finds generated files whose source is gone, and leaves hand-written ones alone', () => {
    const base = temporaryRoot()
    write(base, '.claude/agents/old.md', `<!-- ${GENERATED_MARKER} -->`)
    write(base, '.claude/agents/mine.md', 'written by hand')
    write(base, '.claude/skills/gone/SKILL.md', `<!-- ${GENERATED_MARKER} -->`)
    write(base, '.codex/agents/kept.toml', `# ${GENERATED_MARKER}`)
    const stale = findStale(base, new Map([['.codex/agents/kept.toml', '']]))
    expect(stale).toEqual(['.claude/agents/old.md', '.claude/skills/gone/SKILL.md'])
  })

  it('reports missing and changed files, and ignores the line endings', () => {
    const base = temporaryRoot()
    write(base, 'same.md', 'a\r\nb\r\n')
    write(base, 'different.md', 'x\n')
    const diff = diffOutputs(
      base,
      new Map([
        ['same.md', 'a\nb\n'],
        ['different.md', 'y\n'],
        ['absent.md', 'z\n'],
      ]),
    )
    expect(diff).toEqual({ missing: ['absent.md'], changed: ['different.md'], stale: [] })
  })
})
