// Pure functions behind scripts/sync-agents.mjs (kept apart so tests can import them).
//
// Canonical files (the only ones to edit):
//   .agents/skills/<name>/SKILL.md   frontmatter: name, description
//   .agents/agents/<name>.md         frontmatter: name, description, tools (neutral names)
//
// Generated copies, and the format facts they rely on (checked 2026-11):
//   .claude/skills/<name>/SKILL.md    Claude Code reads project skills from .claude/skills.
//                                     https://code.claude.com/docs/en/skills
//   .claude/agents/<name>.md          frontmatter name, description, tools ("Read, Grep, ...").
//                                     https://code.claude.com/docs/en/sub-agents
//   .github/agents/<name>.agent.md    Copilot custom agents; frontmatter name, description, tools
//                                     with aliases read/search/edit/execute/web.
//                                     https://docs.github.com/en/copilot/reference/custom-agents-configuration
//                                     https://docs.github.com/en/copilot/how-tos/copilot-cli/customize-copilot/create-custom-agents-for-cli
//   .codex/agents/<name>.toml         Codex custom agents; required keys name, description,
//                                     developer_instructions; there is no tools key.
//                                     https://learn.chatgpt.com/docs/agent-configuration/subagents
// Not generated, because the canonical files are already read there:
//   .agents/skills/                   Codex (https://learn.chatgpt.com/docs/build-skills) and
//                                     Copilot (https://docs.github.com/en/copilot/how-tos/copilot-on-github/customize-copilot/customize-cloud-agent/add-skills,
//                                     which lists .github/skills, .claude/skills and .agents/skills).
// Instruction files are written by hand: CLAUDE.md, AGENTS.md (Codex, Copilot) and
// .github/copilot-instructions.md
// (https://docs.github.com/en/copilot/how-tos/configure-custom-instructions/add-repository-instructions).

import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs'
import { join } from 'node:path'

export const SKILLS_SOURCE = '.agents/skills'
export const AGENTS_SOURCE = '.agents/agents'

/** Text that marks a file as generated. Stale-file cleanup only touches files that contain it. */
export const GENERATED_MARKER = 'Generated by scripts/sync-agents.mjs'

/** Neutral tool names accepted in canonical agents, and what each tool calls them. */
export const TOOL_NAMES = {
  read: { claude: ['Read'], copilot: ['read'] },
  search: { claude: ['Grep', 'Glob'], copilot: ['search'] },
  edit: { claude: ['Edit', 'Write'], copilot: ['edit'] },
  run: { claude: ['Bash'], copilot: ['execute'] },
  web: { claude: ['WebFetch'], copilot: ['web'] },
}

export const KEBAB_CASE = /^[a-z][a-z0-9]*(-[a-z0-9]+)*$/

/** Line endings are normalised so a Windows checkout compares equal to what is generated. */
export function normalizeNewlines(text) {
  return text.replace(/\r\n?/g, '\n')
}

function unquote(value) {
  if (/^".*"$/.test(value)) {
    return JSON.parse(value)
  }
  if (/^'.*'$/.test(value)) {
    return value.slice(1, -1).replace(/''/g, "'")
  }
  return value
}

/** Reads `key: value` frontmatter (single-line values only) and returns it with the body. */
export function parseFrontmatter(text) {
  const match = /^---\n([\s\S]*?)\n---\n?([\s\S]*)$/.exec(normalizeNewlines(text))
  if (!match) {
    throw new Error('missing frontmatter')
  }
  const data = {}
  for (const line of (match[1] ?? '').split('\n')) {
    if (line.trim() === '') {
      continue
    }
    const pair = /^([A-Za-z][\w-]*):\s*(.*)$/.exec(line)
    if (!pair) {
      throw new Error(`unsupported frontmatter line: ${line}`)
    }
    data[pair[1] ?? ''] = unquote((pair[2] ?? '').trim())
  }
  return { data, body: (match[2] ?? '').replace(/^\n+/, '') }
}

/** Plain YAML scalar when it is safe, a JSON (double-quoted) string otherwise. */
function yamlScalar(value) {
  const safe = /^[A-Za-z0-9(`]/.test(value) && !/:(\s|$)|\s#/.test(value)
  return safe ? value : JSON.stringify(value)
}

function readCanonicalFile(root, relativePath) {
  const { data, body } = parseFrontmatter(readFileSync(join(root, relativePath), 'utf8'))
  return { path: relativePath, data, body }
}

/** Loads every canonical skill and agent, sorted by name. */
export function loadCanonical(root) {
  const skillsDir = join(root, SKILLS_SOURCE)
  const agentsDir = join(root, AGENTS_SOURCE)
  const skills = existsSync(skillsDir)
    ? readdirSync(skillsDir)
        .filter((entry) => statSync(join(skillsDir, entry)).isDirectory())
        .sort()
        .map((folder) => ({
          folder,
          ...readCanonicalFile(root, `${SKILLS_SOURCE}/${folder}/SKILL.md`),
        }))
    : []
  const agents = existsSync(agentsDir)
    ? readdirSync(agentsDir)
        .filter((entry) => entry.endsWith('.md'))
        .sort()
        .map((file) => ({
          folder: file.replace(/\.md$/, ''),
          ...readCanonicalFile(root, `${AGENTS_SOURCE}/${file}`),
        }))
    : []
  return { skills, agents }
}

/** Neutral tool names of a canonical agent, in the order written. */
export function agentTools(agent) {
  return (agent.data.tools ?? '')
    .split(',')
    .map((tool) => tool.trim())
    .filter(Boolean)
}

/** Problems of the canonical files, as readable messages. Empty when everything is valid. */
export function validateCanonical({ skills, agents }) {
  const problems = []
  const seen = new Set()
  const check = (item) => {
    const where = item.path
    const { name, description } = item.data
    if (!name) problems.push(`${where}: missing name`)
    if (!description) problems.push(`${where}: missing description`)
    if (name && !KEBAB_CASE.test(name)) problems.push(`${where}: name "${name}" is not kebab-case`)
    if (name && name !== item.folder) {
      problems.push(`${where}: name "${name}" does not match "${item.folder}"`)
    }
    // The Agent Skills format caps descriptions at 1024 characters.
    if (description && description.length > 1024) problems.push(`${where}: description too long`)
    if (item.body.trim() === '') problems.push(`${where}: empty body`)
    // A skill and an agent may share a name in theory, but it would confuse every tool.
    if (name && seen.has(name)) problems.push(`${where}: "${name}" is used twice`)
    seen.add(name)
  }
  skills.forEach(check)
  agents.forEach((agent) => {
    check(agent)
    const tools = agentTools(agent)
    if (tools.length === 0) problems.push(`${agent.path}: missing tools`)
    for (const tool of tools) {
      if (!(tool in TOOL_NAMES)) problems.push(`${agent.path}: unknown tool "${tool}"`)
    }
  })
  return problems
}

function markerLine(item) {
  return `${GENERATED_MARKER} from ${item.path}. Edit that file, then run \`npm run sync:agents\`.`
}

function frontmatter(entries) {
  return `---\n${entries.map(([key, value]) => `${key}: ${value}`).join('\n')}\n---\n`
}

function targetTools(agent, tool) {
  return [...new Set(agentTools(agent).flatMap((name) => TOOL_NAMES[name]?.[tool] ?? []))]
}

export function renderClaudeSkill(skill) {
  const head = frontmatter([
    ['name', yamlScalar(skill.data.name)],
    ['description', yamlScalar(skill.data.description)],
  ])
  return `${head}\n<!-- ${markerLine(skill)} -->\n\n${skill.body}`
}

export function renderClaudeAgent(agent) {
  const head = frontmatter([
    ['name', yamlScalar(agent.data.name)],
    ['description', yamlScalar(agent.data.description)],
    ['tools', targetTools(agent, 'claude').join(', ')],
  ])
  return `${head}\n<!-- ${markerLine(agent)} -->\n\n${agent.body}`
}

export function renderCopilotAgent(agent) {
  const tools = targetTools(agent, 'copilot')
    .map((tool) => JSON.stringify(tool))
    .join(', ')
  const head = frontmatter([
    ['name', yamlScalar(agent.data.name)],
    ['description', yamlScalar(agent.data.description)],
    ['tools', `[${tools}]`],
  ])
  return `${head}\n<!-- ${markerLine(agent)} -->\n\n${agent.body}`
}

/** Codex has no tools key, so an agent without `edit` is told in its instructions to stay read-only. */
export function renderCodexAgent(agent) {
  const readOnly = !agentTools(agent).includes('edit')
  const note = readOnly ? 'This agent is read-only: do not create, edit or delete files.\n\n' : ''
  const instructions = `${note}${agent.body}`.trimEnd()
  const quotes = "'''"
  if (instructions.includes(quotes)) {
    throw new Error(`${agent.path}: the body cannot contain three single quotes in a row`)
  }
  return [
    `# ${markerLine(agent)}`,
    `name = ${JSON.stringify(agent.data.name)}`,
    `description = ${JSON.stringify(agent.data.description)}`,
    `developer_instructions = ${quotes}`,
    instructions,
    quotes,
    '',
  ].join('\n')
}

/** Every generated file: relative path to content. */
export function buildOutputs({ skills, agents }) {
  const outputs = new Map()
  for (const skill of skills) {
    outputs.set(`.claude/skills/${skill.data.name}/SKILL.md`, renderClaudeSkill(skill))
  }
  for (const agent of agents) {
    const name = agent.data.name
    outputs.set(`.claude/agents/${name}.md`, renderClaudeAgent(agent))
    outputs.set(`.github/agents/${name}.agent.md`, renderCopilotAgent(agent))
    outputs.set(`.codex/agents/${name}.toml`, renderCodexAgent(agent))
  }
  return outputs
}

/** Folders that hold generated files. `nested` means one subfolder per skill. */
const GENERATED_LOCATIONS = [
  { dir: '.claude/skills', nested: true },
  { dir: '.claude/agents', nested: false },
  { dir: '.github/agents', nested: false },
  { dir: '.codex/agents', nested: false },
]

/** Files in generated folders that carry the marker but are no longer produced. */
export function findStale(root, outputs) {
  const stale = []
  for (const { dir, nested } of GENERATED_LOCATIONS) {
    const base = join(root, dir)
    if (!existsSync(base)) continue
    for (const entry of readdirSync(base)) {
      const relative = nested ? `${dir}/${entry}/SKILL.md` : `${dir}/${entry}`
      const file = join(root, relative)
      if (outputs.has(relative) || !existsSync(file) || !statSync(file).isFile()) continue
      if (readFileSync(file, 'utf8').includes(GENERATED_MARKER)) stale.push(relative)
    }
  }
  return stale.sort()
}

/** Compares what is on disk with what would be generated. */
export function diffOutputs(root, outputs) {
  const missing = []
  const changed = []
  for (const [relative, content] of outputs) {
    const file = join(root, relative)
    if (!existsSync(file)) {
      missing.push(relative)
    } else if (normalizeNewlines(readFileSync(file, 'utf8')) !== content) {
      changed.push(relative)
    }
  }
  return { missing, changed, stale: findStale(root, outputs) }
}

/** Names of the npm scripts that a text asks the reader to run (`npm run x`). */
export function npmScriptsMentioned(text) {
  return [...text.matchAll(/npm run ([a-z][\w:-]*)/g)].map((match) => match[1] ?? '')
}

/** Repository paths written in backticks (`src/...`), without globs and placeholders. */
export function repoPathsMentioned(text) {
  const pattern = /`((?:src|tests|docs|scripts|public|\.agents|\.github)\/[^`\s]*)`/g
  return [...text.matchAll(pattern)]
    .map((match) => match[1] ?? '')
    .filter((path) => !/[*<>{}|]/.test(path))
}
